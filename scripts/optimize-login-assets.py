"""Delivery derivatives only; retain the original Figma PNGs unchanged."""
from pathlib import Path
from PIL import Image
from fontTools.ttLib import TTFont
import base64

root = Path(__file__).resolve().parents[1] / 'public' / 'assets' / 'login'
before = after = 0
for source in root.glob('*.png'):
    image = Image.open(source)
    image.thumbnail((1536, 1024) if source.stem in ('village', 'signboard') else (1200, 400))
    target = source.with_suffix('.webp')
    image.save(target, 'WEBP', quality=86, method=6)
    before += source.stat().st_size
    after += target.stat().st_size
    print(f'{target.name}: {target.stat().st_size:,} bytes')
print(f'Total: {before:,} -> {after:,} bytes ({1 - after / before:.1%} smaller)')
for name, size in [('village', (768, 512)), ('logo', (600, 200))]:
    image = Image.open(root / f'{name}.png')
    image.thumbnail(size)
    target = root / f'{name}-mobile.webp'
    image.save(target, 'WEBP', quality=80, method=6)
    print(f'{target.name}: {target.stat().st_size:,} bytes')
font = TTFont(root.parents[1] / 'fonts' / 'PixelifySans.ttf')
font.flavor = 'woff2'
font_path = root.parents[1] / 'fonts' / 'PixelifySans.woff2'
font.save(font_path)
encoded = base64.b64encode(font_path.read_bytes()).decode('ascii')
(root.parents[2] / 'src' / 'pixel-font.css').write_text(
    '/* Generated by scripts/optimize-login-assets.py; license: public/fonts/PixelifySans-OFL.txt */\n'
    '@font-face { font-family: "Pixelify Sans"; src: url("data:font/woff2;base64,' + encoded + '") format("woff2"); '
    'font-style: normal; font-weight: 400 700; font-display: swap; }\n', encoding='utf8')
